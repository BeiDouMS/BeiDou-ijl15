// 显示模式表补丁：修复"启动时弹 -214xxxxxxx 数字错误框然后退出"
//
// 客户端启动时会用 IDirect3D8::EnumAdapterModes 枚举显卡支持的显示模式，
// 在里面找 config.ini 里配置的 width x height。找不到就直接放弃启动，
// 连 CreateDevice 都不会调（所以窗口模式之类的设置根本救不了）。
//
// 实测两个失败环境（2026-08-16）：
//   * 远程桌面 RDP 会话：整张模式表只有 1 条，就是桌面自身的分辨率
//   * macOS 内置 Retina 屏（Whisky/wine 7.7, M2 Max）：264 条全是苹果的 16:10
//     缩放档（960x600 / 1280x800 / 1512x945 ...），没有任何标准 PC 分辨率
//   * 插外接显示器就正常，因为外接屏会上报标准分辨率表
// 两台机器的刷新率其实都正常上报，所以主因是分辨率不在表里，不是刷新率问题。
//
// 本模块的做法：目标分辨率不在真实模式表里时，往表尾补几条（目标分辨率 x
// {桌面像素格式, R5G6B5} x {桌面刷新率, 60Hz}）。客户端是窗口模式，找到模式后
// 并不会真的去切显示模式，所以这个"谎"不会有副作用。
//
// 目标分辨率本来就在表里就一条都不补，因此对能正常启动的机器毫无影响。

void ModeTableFix_Install(bool enable);
